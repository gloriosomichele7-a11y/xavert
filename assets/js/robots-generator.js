"use strict";

function initRobotsGenerator() {
  const userAgent = document.getElementById("userAgent");
  const disallow = document.getElementById("disallow");
  const allow = document.getElementById("allow");
  const crawlDelay = document.getElementById("crawlDelay");
  const sitemap = document.getElementById("sitemap");

  const output = document.getElementById("output");
  const generateBtn = document.getElementById("generateBtn");
  const sampleBtn = document.getElementById("sampleBtn");
  const clearBtn = document.getElementById("clearBtn");
  const copyBtn = document.getElementById("copyBtn");
  const downloadBtn = document.getElementById("downloadBtn");
  const message = document.getElementById("message");

  const required = [
    userAgent,
    disallow,
    allow,
    crawlDelay,
    sitemap,
    output,
    generateBtn,
    sampleBtn,
    clearBtn,
    copyBtn,
    downloadBtn,
    message,
  ];

  if (required.some((element) => !element)) {
    console.error("Robots.txt Generator: HTML and JS do not match.");
    return;
  }

  function setInlineMessage(text = "", type = "info") {
    const safeType = ["success", "error", "info"].includes(type)
      ? type
      : "info";

    message.textContent = text;
    message.classList.remove(
      "message-success",
      "message-error",
      "message-info",
    );

    if (text) {
      message.classList.add(`message-${safeType}`);
    }
  }

  function notify(text, type = "info") {
    setInlineMessage(text, type);

    if (typeof window.showMessage === "function") {
      window.showMessage(text, type);
    }
  }

  function normalizePath(value) {
    const text = value.trim();

    if (!text) {
      return "";
    }

    return text.startsWith("/") ? text : `/${text}`;
  }

  function normalizeSitemapUrl(value) {
    const text = value.trim();

    if (!text) {
      return "";
    }

    let url;

    try {
      url = new URL(text);
    } catch {
      throw new Error("Please enter a valid Sitemap URL.");
    }

    if (!["http:", "https:"].includes(url.protocol)) {
      throw new Error("Sitemap URL must use HTTP or HTTPS.");
    }

    return url.href;
  }

  function resetOutput() {
    output.value = "";
    copyBtn.disabled = true;
    downloadBtn.disabled = true;
  }

  function invalidateResult() {
    if (output.value) {
      resetOutput();
    }

    setInlineMessage("");
  }

  function generateRobots({ announce = true } = {}) {
    const delayText = crawlDelay.value.trim();

    if (delayText) {
      const delay = Number(delayText);

      if (!Number.isFinite(delay) || delay < 0) {
        resetOutput();
        notify("Crawl delay cannot be negative.", "error");
        crawlDelay.focus();
        return false;
      }
    }

    let sitemapUrl = "";

    try {
      sitemapUrl = normalizeSitemapUrl(sitemap.value);
    } catch (error) {
      resetOutput();

      notify(
        error instanceof Error ? error.message : "Invalid Sitemap URL.",
        "error",
      );

      sitemap.focus();
      return false;
    }

    const lines = [
      "# robots.txt generated by XAVERT",
      "# https://xavert.com",
      "",
      `User-agent: ${userAgent.value}`,
      `Disallow: ${normalizePath(disallow.value)}`,
    ];

    const allowPath = normalizePath(allow.value);

    if (allowPath) {
      lines.push(`Allow: ${allowPath}`);
    }

    if (delayText) {
      lines.push(`Crawl-delay: ${delayText}`);
    }

    if (sitemapUrl) {
      lines.push("", `Sitemap: ${sitemapUrl}`);
    }

    output.value = `${lines.join("\n")}\n`;

    copyBtn.disabled = false;
    downloadBtn.disabled = false;

    if (announce) {
      setInlineMessage("Action completed successfully.", "success");

      if (typeof window.showActionSuccess === "function") {
        window.showActionSuccess();
      } else if (typeof window.showMessage === "function") {
        window.showMessage("Action completed successfully.", "success");
      }
    }

    return true;
  }

  function loadSample() {
    userAgent.value = "*";
    disallow.value = "/admin/";
    allow.value = "/";
    crawlDelay.value = "";
    sitemap.value = "https://xavert.com/sitemap.xml";

    resetOutput();
    setInlineMessage("");

    const generated = generateRobots({ announce: false });

    if (!generated) {
      return;
    }

    setInlineMessage("Sample loaded successfully.", "success");

    if (typeof window.showSampleSuccess === "function") {
      window.showSampleSuccess();
    } else if (typeof window.showMessage === "function") {
      window.showMessage("Sample loaded successfully.", "success");
    }

    userAgent.focus();
  }

  async function copyOutput() {
    if (!output.value) {
      notify("Nothing to copy.", "error");
      return;
    }

    if (typeof window.xavertCopyText !== "function") {
      notify("Copy utility is unavailable.", "error");
      return;
    }

    await window.xavertCopyText(output.value);
  }

  function downloadOutput() {
    if (!output.value) {
      notify("Nothing to download.", "error");
      return;
    }

    if (typeof window.downloadFile !== "function") {
      notify("Download utility is unavailable.", "error");
      return;
    }

    window.downloadFile("robots.txt", output.value, "text/plain;charset=utf-8");
  }

  function clearAll() {
    userAgent.value = "*";
    disallow.value = "";
    allow.value = "";
    crawlDelay.value = "";
    sitemap.value = "";

    resetOutput();
    setInlineMessage("");
    userAgent.focus();
  }

  [disallow, allow, crawlDelay, sitemap].forEach((element) => {
    element.addEventListener("input", invalidateResult);
  });

  userAgent.addEventListener("change", invalidateResult);

  generateBtn.addEventListener("click", () => {
    generateRobots();
  });

  sampleBtn.addEventListener("click", loadSample);
  clearBtn.addEventListener("click", clearAll);

  copyBtn.addEventListener("click", () => {
    void copyOutput();
  });

  downloadBtn.addEventListener("click", downloadOutput);

  resetOutput();
}

initRobotsGenerator();
